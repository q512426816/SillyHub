/**
 * dsh-settings.ts —— per-session DSH_HOME 配置写盘器 + 密钥 env 注入器。
 *
 * 2026-10-15-dsh-engine-acp task-04（FR-05 模型路由）。照 codex-settings.ts /
 * pi-settings.ts 先例（provider-file-settings.ts 薄适配消费）；实现体放本文件
 * 而非 credential-injector.ts（allowed_paths 边界 + 注册表 envInjector 契约只
 * 要求返回 CredentialInjector 接口实例，实现位置自由——type-only import 无环）。
 *
 * 模型路由形态：per-session DSH_HOME 下写 profiles/acp/ 三件套（package.json +
 * pnpm-workspace.yaml + cordis.patch.yml）的 llm-pi-ai 自定义路由（api 按 base_url
 * 形态判 anthropic-messages / openai-completions；apiKeyEnv 指向 SILLYHUB_DSH_API_KEY
 * ——密钥本体经 DshCredentialInjector 注入子进程 env，patch 只存变量名）。
 * 会话/轮级模型选择经 ACP session/set_config_option 扁平形状，模型值 =
 * `["sillyhub","<model>"]`（valueId 数组串，dsh-acp-driver 消费 DSH_PROVIDER_ID 组装）。
 * 依据：dsh 0.2.0-rc.2 内 @agentclientprotocol/sdk zod schema + llm-pi-ai lib
 * profile schema（2026-10-17 探针三轮钉板，详见 writeDshHome 头注）。
 *
 * 无 provider_config / 配置不充分（缺 base_url/api_key/model 或 openai_chat
 * 代理形态）→ 不写盘不注入（dsh 用其本机默认模型，与 codex/pi 无配置先例一致；
 * 建/切会话 warnings 提示管线已覆盖）。
 */

import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import type { CredentialInjector } from './credential-injector.js';
import type { ProviderConfig } from './types.js';

/** 密钥 env 变量名（patch 的 apiKeyEnv 引用它；注入器写它）。 */
export const DSH_API_KEY_ENV = 'SILLYHUB_DSH_API_KEY';

/** 托管 provider 键名（patch 内 providers.<键>；驱动模型值 `["<键>","<model>"]` 引用）。 */
export const DSH_PROVIDER_ID = 'sillyhub';

/** patch 相对路径（DSH_HOME 下的 acp profile 覆盖层，dsh HMR 下次请求生效）。 */
const PATCH_DIR_PARTS = join('profiles', 'acp');

/** openai_chat 代理形态不写盘（对齐 pi isPiFormSufficient 同款排除）。 */
function isProxyForm(provider: ProviderConfig): boolean {
  return provider.api_format === 'openai_chat';
}

function nonEmpty(value: unknown): string | undefined {
  return typeof value === 'string' && value.length > 0 ? value : undefined;
}

/**
 * 写盘门槛：base_url + api_key + model 三者齐且非代理形态（对齐 pi
 * isPiFormSufficient 判据族；官方端点形态 base_url 空 → false → 调用方 warn 跳过）。
 */
export function isDshFormSufficient(provider: ProviderConfig): boolean {
  return (
    !isProxyForm(provider) &&
    nonEmpty(provider.base_url) !== undefined &&
    nonEmpty(provider.api_key) !== undefined &&
    (nonEmpty(provider.default_fallback_model) ?? nonEmpty(provider.model)) !== undefined
  );
}

/**
 * base_url 形态 → llm-pi-ai api 协议值：含 'anthropic' → anthropic-messages，
 * 其余 → openai-completions（openai-responses 为 dsh 特定路由，平台 LlmProvider
 * 无该形态标注，不猜测）。
 */
function apiFormFor(baseUrl: string): 'anthropic-messages' | 'openai-completions' {
  return baseUrl.toLowerCase().includes('anthropic')
    ? 'anthropic-messages'
    : 'openai-completions';
}

/**
 * 写 per-session DSH_HOME 的 acp profile 覆盖层。
 *
 * dsh 0.2.0-rc.2 布局（2026-10-17 探针钉板，三轮实测）：
 *   1. `profiles/acp/package.json` 必须存在且 `dsh.profile.bundles` 为模板清单
 *      `["@deepseek-ai/dsh-base","@deepseek-ai/dsh-acp-app"]`——缺失时引擎会按
 *      模板自愈（首次 boot 自动 seed），显式写盘为确定性兜底；
 *   2. `pnpm-workspace.yaml` 随模板（仅布局占位）；
 *   3. `cordis.patch.yml` 为 id 定向 config 覆盖（ providers.<route> 形状），
 *      **禁止携带 compat 块**——rc.2 的 compatProfile 字段集已漂移，compat 块
 *      存在即整条 provider 被静默拒收（探针实证：带 compat = 模型目录无
 *      sillyhub 组；去 compat = 出现且可选）。catalog 默认值由引擎按 api
 *      协议自动补齐。
 *
 * @param dshHome per-session DSH_HOME 目录（provider-file-settings 已建）。
 * @param provider 平台 ProviderConfig（已过 isDshFormSufficient 门槛）。
 */
export async function writeDshHome({
  dshHome,
  provider,
}: {
  dshHome: string;
  provider: ProviderConfig;
}): Promise<void> {
  const baseUrl = nonEmpty(provider.base_url)!;
  const model = nonEmpty(provider.default_fallback_model) ?? nonEmpty(provider.model)!;
  const patchDir = join(dshHome, PATCH_DIR_PARTS);
  await mkdir(patchDir, { recursive: true });
  // 手写 YAML（零依赖纪律，G-05 同款）：单条 llm-pi-ai 路由覆盖层（无 compat 块，
  // 见函数头 dsh 0.2.0-rc.2 布局说明）。
  const yaml = [
    '# Generated by sillyhub-daemon (per-session DSH_HOME, engine route) - do not edit',
    '- id: llm-pi-ai',
    '  config:',
    '    providers:',
    `      ${DSH_PROVIDER_ID}:`,
    `        displayName: SillyHub`,
    `        api: ${apiFormFor(baseUrl)}`,
    `        baseURL: ${baseUrl}`,
    `        apiKeyEnv: ${DSH_API_KEY_ENV}`,
    '        models:',
    `          - id: ${model}`,
    `            name: ${model}`,
    '            contextWindow: 200000',
    '            maxTokens: 128000',
    '            input:',
    '              - text',
    '            reasoningEfforts: false',
    '',
  ].join('\n');
  await Promise.all([
    writeFile(join(patchDir, 'package.json'), JSON.stringify({
      name: 'dsh-profile-acp',
      private: true,
      dependencies: {},
      dsh: { profile: { bundles: ['@deepseek-ai/dsh-base', '@deepseek-ai/dsh-acp-app'] } },
    }, null, 2) + '\n', 'utf8'),
    writeFile(join(patchDir, 'pnpm-workspace.yaml'), 'packages:\n  - .\n\nnodeLinker: hoisted\nautoInstallPeers: false\n', 'utf8'),
    writeFile(join(patchDir, 'cordis.patch.yml'), yaml, 'utf8'),
  ]);
}

/**
 * dsh env 层注入器：api_key → SILLYHUB_DSH_API_KEY（patch 的 apiKeyEnv 引用），
 * extra_env 透传。纯函数（R-02 不泄漏：返回值仅内存 env 用）。
 */
export class DshCredentialInjector implements CredentialInjector {
  readonly agentKind = 'dsh';

  toEnv(c: ProviderConfig): Record<string, string> {
    const env: Record<string, string> = {};
    if (c.api_key) {
      env[DSH_API_KEY_ENV] = c.api_key;
    }
    for (const [k, v] of Object.entries(c.extra_env ?? {})) {
      if (typeof v === 'string' && v.length > 0) {
        env[k] = v;
      }
    }
    return env;
  }
}
